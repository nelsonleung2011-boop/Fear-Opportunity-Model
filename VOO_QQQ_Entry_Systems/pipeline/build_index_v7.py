#!/usr/bin/env python3
"""Assemble the self-contained v7 dashboard (index_v7.html). v1-v6 untouched."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "dashboard_v7_template.html"
RENDER = ROOT / "pipeline" / "v7_render.js"
PAYLOAD = ROOT / "data" / "evidence_v7.json"
OUTPUT = ROOT / "index_v7.html"


def main() -> None:
    if "--refresh" in sys.argv or not PAYLOAD.exists():
        sys.path.insert(0, str(ROOT))
        from pipeline import ops_price
        from pipeline.entry_decision_engine import run
        # Dynamically dated frames: never use the inherited frozen 2026-11-16 loader.
        run(frames=ops_price.load_frames())

    data = json.loads(PAYLOAD.read_text(encoding="utf-8"))
    tpl = TEMPLATE.read_text(encoding="utf-8")
    js = RENDER.read_text(encoding="utf-8")

    # Operational + provenance payloads are generated by the daily pipeline.
    # Fall back to generating them here so a standalone build still works.
    OPSDIR = ROOT / "data" / "ops"
    status_path = OPSDIR / "status.json"
    audit_path = OPSDIR / "data_audit.json"
    if status_path.exists():
        data["ops"] = json.loads(status_path.read_text(encoding="utf-8"))
    else:
        data["ops"] = {"status": {"last_run": None, "mode": "not run yet",
                                  "status": "idle", "refresh_status": "not run",
                                  "sources_updated": 0, "sources_failed": 0},
                       "percentiles": {}, "rules": [], "recent_alerts": [],
                       "score_history": [], "weekly_summary": {}, "email_config":
                       {"configured": False, "mode": "dry-run"}, "email_preview": {},
                       "setup": {"command": "python pipeline/ops_daily.py", "notes": []}}
    if audit_path.exists():
        data["data_audit"] = json.loads(audit_path.read_text(encoding="utf-8"))
    else:
        sys.path.insert(0, str(ROOT))
        from pipeline import ops_data_audit
        data["data_audit"] = ops_data_audit.build(data)

    def clean(obj):
        """Bare NaN/Infinity are not valid JSON and break browser JSON.parse."""
        import math
        if isinstance(obj, float):
            return None if not math.isfinite(obj) else obj
        if isinstance(obj, dict):
            return {k: clean(v) for k, v in obj.items()}
        if isinstance(obj, (list, tuple)):
            return [clean(v) for v in obj]
        return obj

    def enc(obj) -> str:
        return (json.dumps(clean(obj), ensure_ascii=False, separators=(",", ":"),
                           allow_nan=False)
                .replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026"))

    if "__PAYLOAD__" not in tpl or "__RENDER_JS__" not in tpl:
        raise SystemExit("v7 template is missing a placeholder")
    html = tpl.replace("__RENDER_JS__", js).replace("__PAYLOAD__", enc(data))
    OUTPUT.write_text(html, encoding="utf-8")

    assert "__PAYLOAD__" not in html and "__RENDER_JS__" not in html
    for needle in ("Market Regime", "WHY THIS SCORE?", "Credit Stress Score",
                   "Opportunity Cost", "Score Audit Trail", "Simple Mode", "Expert Mode",
                   "Market Internals", "Cash deployment guidance",
                   "DATA &amp; SOURCES", "OPERATIONS", "SCORE INPUT LEDGER",
                   "ALERT RULES", "['data','DATA &amp; SOURCES']", "['ops','OPERATIONS']",
                   "id=\"tab-' + t[0]", "id=\"pane-data\"", "id=\"pane-ops\"",
                   "addEventListener('click', handleClick)"):
        assert needle in html, f"missing content: {needle}"
    for forbidden in ("Timing Advantage", "Evidence Insufficient", "Predicted 12M Return",
                      "XGBoost", "Random Forest", "AUC"):
        assert forbidden not in html, f"v7 must not contain: {forbidden}"
    assert set(data["instruments"]) == {"VOO", "QQQ"}
    assert data["hero"]["always_answered"] is True
    assert "deployment" in data["hero"]
    assert "explain" in data["instruments"]["VOO"]
    assert "audit" in data["instruments"]["VOO"]
    assert len(data["analogues"]) == 5
    print(f"[build] wrote {OUTPUT.name} ({OUTPUT.stat().st_size / 1024:.0f} KB)")
    h = data['hero']
    print(f"[build] as-of {data['meta']['as_of']} | regime {h['market_regime']} "
          f"({h['regime_confidence']}) | valuation {h['valuation']} | "
          f"opportunity {h['opportunity']} | deployment {h['deployment']}")


if __name__ == "__main__":
    main()
